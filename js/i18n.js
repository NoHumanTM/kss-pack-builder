let lang = "en";
try {
  lang = localStorage.getItem("kss-lang") || (navigator.language || "en").slice(0, 2);
} catch (e) { /* sin almacenamiento */ }
if (!STRINGS[lang]) lang = "en";

export function getLang() {
  return lang;
}

export function setLang(value) {
  if (!STRINGS[value]) return;
  lang = value;
  try { localStorage.setItem("kss-lang", value); } catch (e) { /* sin almacenamiento */ }
  document.documentElement.lang = value;
}

export function t(key, ...args) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\d+)\}/g, (_, i) => (args[i] ?? ""));
}

// Rellena los elementos con data-i18n / data-i18n-placeholder
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}
